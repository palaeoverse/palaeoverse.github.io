#!/usr/bin/env Rscript

# Write _sidebars.yml: one sidebar for every module with more than one web page.
#
# Quarto only reads sidebar definitions from the project config, so _quarto.yml
# pulls this file in with `metadata-files: [_sidebars.yml]`. Register this as
# `pre-render` so it runs before every render.
#
# Only pages that render to html are shown, and a module must have at least two
# pages rendered to html to have a siderbar. Files that only render to revealjs
# are not shown in the sidebar and do not count as web pages.
#
# Usage: Rscript sync_sidebars.r [modules_dir]   (run from the project root)
#   modules_dir: where the module directories live, relative to the project
#                root (default "."; "training/modules" on the website)

library(yaml)

args        <- commandArgs(trailingOnly = TRUE)
modules_dir <- if (length(args) > 0) args[[1]] else "."
out         <- "_sidebars.yml"

front_matter <- function(path) {
  lines <- readLines(path, warn = FALSE)
  fences <- which(trimws(lines) == "---")
  if (length(fences) < 2 || fences[[1]] != 1) return(list())
  meta <- tryCatch(yaml.load(paste(lines[2:(fences[[2]] - 1)], collapse = "\n")),
                   error = function(e) NULL)
  if (is.list(meta)) meta else list()
}

# html (or e.g. live-html) unless every format is a non-html one like revealjs
is_web_page <- function(meta) {
  fmt <- meta$format
  if (is.null(fmt)) return(TRUE)
  fmts <- if (is.list(fmt)) names(fmt) else as.character(fmt)
  any(grepl("html$", fmts))
}

# web pages in `dir`, non-recursively, as list(path, order), sorted as Quarto does
web_pages <- function(dir) {
  files <- list.files(dir, pattern = "[.]qmd$")
  files <- files[!grepl("^_", files)]   # Quarto doesn't render _-prefixed files
  pages <- lapply(file.path(dir, files), function(p) {
    meta <- front_matter(p)
    if (!is_web_page(meta)) return(NULL)
    list(path = sub("^[.]/", "", p), order = suppressWarnings(as.numeric(meta$order[1])))
  })
  pages <- Filter(Negate(is.null), pages)
  order_key <- vapply(pages, function(p) if (length(p$order)) p$order else Inf, numeric(1))
  name_key  <- toupper(basename(vapply(pages, `[[`, "", "path")))
  pages[order(order_key, name_key)]
}

# a directory as a sidebar section headed by its index, or NULL if it has no
# web pages; `n` counts the pages so single-page modules can be skipped
section <- function(dir) {
  pages   <- web_pages(dir)
  is_idx  <- basename(vapply(pages, `[[`, "", "path")) == "index.qmd"
  index   <- pages[is_idx]
  subdirs <- list.dirs(dir, full.names = TRUE, recursive = FALSE)
  subdirs <- subdirs[!grepl("^[._]", basename(subdirs)) & !grepl("_files$", subdirs)]
  subs    <- Filter(Negate(is.null), lapply(subdirs[order(toupper(basename(subdirs)))], section))

  contents <- c(lapply(pages[!is_idx], `[[`, "path"), lapply(subs, `[[`, "item"))
  n <- length(pages) + sum(vapply(subs, `[[`, 0, "n"))
  if (n == 0) return(NULL)

  title <- if (length(index)) front_matter(index[[1]]$path)$title
  item  <- list(section = if (is.null(title)) basename(dir) else title)
  if (length(index)) item$href <- index[[1]]$path
  if (length(contents)) item$contents <- contents
  list(item = item, n = n)
}

modules <- list.dirs(modules_dir, full.names = TRUE, recursive = FALSE)
modules <- modules[!grepl("^[._]", basename(modules))]   # skip _templates, .git, ...

sidebars <- list()
for (m in modules) {
  s <- section(m)
  if (is.null(s) || s$n < 2) next
  path <- sub("^[.]/", "", m)
  sidebars[[length(sidebars) + 1]] <- list(
    id        = gsub("/", "-", path),
    style     = "floating",
    alignment = "left",
    contents  = list(s$item)
  )
}

content <- c(
  paste0("# ", out, " -- AUTOGENERATED by sync_sidebars.r, DO NOT EDIT."),
  if (length(sidebars) == 0) "website: {}" else
    strsplit(as.yaml(list(website = list(sidebar = sidebars))), "\n")[[1]]
)

# only rewrite when changed, so preview doesn't loop on a file-change reload
if (!file.exists(out) || !identical(readLines(out, warn = FALSE), content)) {
  writeLines(content, out)
  message("sync_sidebars: wrote ", out, " (", length(sidebars), " sidebar(s))")
}
